/** 节点主题（含粒子参数与氛围色），未知节点回退 departure */
function getNodeTheme(nodeId) {
  return THEMES[NODE_THEME_MAP[nodeId]] || THEMES.departure;
}

/** 节点图标折线集，未知节点回退 null（内核画默认星形） */
function getNodeIcon(nodeId) {
  return NODE_ICONS[nodeId] || null;
}

/**
 * 章节主题：由章节 nodeIds 取其首节点主题（章节内节点同属一个主题区段，
 * 见 NODE_THEME_MAP；管理端调整章节归属后主题跟节点走，视觉不漂移）。
 */
function getChapterTheme(chapter) {
  const ids = (chapter && chapter.nodeIds) || [];
  return getNodeTheme(ids[0]);
}

module.exports = { PALETTE, THEMES, getNodeTheme, getNodeIcon, getChapterTheme };
